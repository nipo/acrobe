# MPSSE shift command flags (OR mask)
WRITE_NEG  = 0x01
BITS       = 0x02
READ_NEG   = 0x04
LSB        = 0x08
WRITE      = 0x10
READ       = 0x20
TMS        = 0x40
MANAGEMENT = 0x80

# Management commands
