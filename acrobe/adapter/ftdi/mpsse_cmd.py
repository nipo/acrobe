LOOPBACK_ENABLE      = MANAGEMENT | 0x04
LOOPBACK_DISABLE     = MANAGEMENT | 0x05
CLK_DIV              = MANAGEMENT | 0x06
SEND_IMMEDIATE       = MANAGEMENT | 0x07
WAIT_ON_HIGH         = MANAGEMENT | 0x08
WAIT_ON_LOW          = MANAGEMENT | 0x09
CLK_DIV5_DISABLE     = MANAGEMENT | 0x0a
CLK_DIV5_ENABLE      = MANAGEMENT | 0x0b
THREE_PHASE_ENABLE   = MANAGEMENT | 0x0c
THREE_PHASE_DISABLE  = MANAGEMENT | 0x0d
CLK_BITS             = MANAGEMENT | 0x0e
CLK_BYTES            = MANAGEMENT | 0x0f
CLK_WAIT_HIGH        = MANAGEMENT | 0x14
CLK_WAIT_LOW         = MANAGEMENT | 0x15
ADAPTIVE_ENABLE      = MANAGEMENT | 0x16
